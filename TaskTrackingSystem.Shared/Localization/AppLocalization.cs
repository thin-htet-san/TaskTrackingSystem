    public static bool IsBurmeseCulture => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("my", StringComparison.OrdinalIgnoreCase);

    public static string Text(string key, string fallback = "")
    {
        var catalog = IsBurmeseCulture ? Burmese : English;
        if (catalog.TryGetValue(key, out var value))
        {
            return value;
        }

        if ((IsBurmeseCulture ? English : Burmese).TryGetValue(key, out value))
        {
            return value;
        }

        return string.IsNullOrWhiteSpace(fallback) ? key : fallback;
    }

    public static string LocalizeDigits(string? value)
    {
        if (!IsBurmeseCulture || string.IsNullOrEmpty(value))
        {
            return value ?? string.Empty;
        }

        return value
            .Replace('0', '၀')
            .Replace('1', '၁')
            .Replace('2', '၂')
            .Replace('3', '၃')
            .Replace('4', '၄')
            .Replace('5', '၅')
            .Replace('6', '၆')
            .Replace('7', '၇')
            .Replace('8', '၈')
            .Replace('9', '၉');
    }

    public static string Number(int value) => LocalizeDigits(value.ToString(CultureInfo.InvariantCulture));

    public static string Number(long value) => LocalizeDigits(value.ToString(CultureInfo.InvariantCulture));

    public static string Number(decimal value, string format = "0.#") => LocalizeDigits(value.ToString(format, CultureInfo.InvariantCulture));

    public static string Number(double value, string format = "0.#") => LocalizeDigits(value.ToString(format, CultureInfo.InvariantCulture));

