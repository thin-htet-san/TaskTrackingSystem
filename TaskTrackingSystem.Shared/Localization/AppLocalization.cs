        if (string.IsNullOrWhiteSpace(description))
        {
            return Text("common.noneRecorded", "None recorded");
        }

        var text = LocalizeDigits(description);
        if (!IsBurmeseCulture)
        {
            return text;
        }

        return text switch
        {
            var value when value.StartsWith("Created project ", StringComparison.OrdinalIgnoreCase) => $"စီမံကိန်း {value["Created project ".Length..]} ကို ဖန်တီးခဲ့သည်",
