    public static string LocalizeNotificationBody(string? body)
    {
        if (string.IsNullOrWhiteSpace(body)) return string.Empty;
        if (!IsBurmeseCulture) return body;

        if (body.StartsWith("You have been assigned a new task: ", StringComparison.OrdinalIgnoreCase))
        {
            return $"သင့်အား လုပ်ငန်းသစ်တစ်ခု တာဝန်ပေးအပ်ထားပါသည် - {body["You have been assigned a new task: ".Length..]}";
        }
        if (body.StartsWith("Task '", StringComparison.OrdinalIgnoreCase) && body.Contains("' changed from "))
        {
            var match = System.Text.RegularExpressions.Regex.Match(body, @"^Task '(?<title>.+)' changed from (?<oldStatus>.+) to (?<newStatus>.+)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
            if (match.Success)
            {
                var title = match.Groups["title"].Value;
                var oldStatus = StatusName(match.Groups["oldStatus"].Value);
                var newStatus = StatusName(match.Groups["newStatus"].Value);
                return $"လုပ်ငန်း '{title}' ၏အခြေအနေသည် '{oldStatus}' မှ '{newStatus}' သို့ ပြောင်းလဲသွားပါသည်";
            }
        }
        if (body.StartsWith("You have been assigned to project '", StringComparison.OrdinalIgnoreCase) && body.EndsWith("'"))
        {
            var projName = body["You have been assigned to project '".Length..^1];
            return $"သင့်အား စီမံကိန်း '{projName}' တွင် တာဝန်ပေးအပ်ထားပါသည်";
        }
        if (body.Contains(" commented on task '") && body.EndsWith("'"))
        {
            var idx = body.IndexOf(" commented on task '", StringComparison.OrdinalIgnoreCase);
            if (idx > 0)
            {
                var actor = body[..idx];
                var taskTitle = body[(idx + " commented on task '".Length)..^1];
                return $"{actor} သည် လုပ်ငန်း '{taskTitle}' တွင် မှတ်ချက်တစ်ခု ရေးသားခဲ့ပါသည်";
            }
        }
        if (body.Contains(" mentioned you in task '") && body.EndsWith("'"))
        {
            var idx = body.IndexOf(" mentioned you in task '", StringComparison.OrdinalIgnoreCase);
            if (idx > 0)
            {
                var actor = body[..idx];
                var taskTitle = body[(idx + " mentioned you in task '".Length)..^1];
                return $"{actor} သည် လုပ်ငန်း '{taskTitle}' တွင် သင့်ကို ရည်ညွှန်းဖော်ပြခဲ့ပါသည်";
            }
        }

        return LocalizeDigits(body);
    }
